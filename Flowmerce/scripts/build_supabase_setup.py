"""Join db/central/000-105 into db/central/supabase_setup.sql (one file to paste into the Supabase SQL editor).

Usage: .venv\\Scripts\\python.exe scripts\\build_supabase_setup.py
"""
from __future__ import annotations

from pathlib import Path

DIR = Path(__file__).resolve().parents[1] / "db" / "central"
FILES = ["000_extensions_and_schemas.sql", "010_ops_setup.sql", "020_ops_orders_shipments.sql",
         "030_ops_tracking.sql", "040_ops_costs_and_feeds.sql", "060_ops_views.sql", "070_seo_tables.sql",
         "080_security.sql", "090_seed.sql", "105_refresh_from_shopify_orders.sql",
         "106_service_role_timeout.sql", "107_flow_board.sql",
         "108_flow_board_amazon.sql",
         "109_amazon_mcf_intake.sql", "111_amazon_mcf_sheet.sql"]

HEADER = """-- =====================================================================================
-- FLOWMERCE · SUPABASE SETUP (one file)
-- Paste into Supabase -> SQL Editor -> Run. Safe to run again. Never changes public.* tables.
-- Then: Project Settings -> Data API -> Exposed schemas -> add "ops".
-- Generated by scripts/build_supabase_setup.py from db/central/000-105. Do not edit by hand.
-- =====================================================================================

"""

FOOTER = """
-- ---------------------------------------------------------------- record what was applied
insert into ops.schema_migrations (file, note)
values ('supabase_setup.sql', 'files 000-105')
on conflict (file) do update set applied_at = now();

-- Optional: fill the tables now instead of waiting for Flowmerce's first refresh:
-- select ops.refresh_from_tracker();
"""


def main() -> None:
    parts = [HEADER]
    for name in FILES:
        parts.append(f"\n-- ##################################################################### {name}\n")
        parts.append((DIR / name).read_text(encoding="utf-8"))
    parts.append(FOOTER)
    out = DIR / "supabase_setup.sql"
    out.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {out.name}: {out.stat().st_size:,} bytes from {len(FILES)} files")


if __name__ == "__main__":
    main()
